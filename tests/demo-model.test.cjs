'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const {webcrypto}=require('node:crypto');
const root=path.resolve(__dirname,'..');
(async()=>{
 const saved=new Map(),sessions=new Map();let failWrites=false;
 const localStorage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>{if(failWrites)throw new Error('quota');saved.set(k,v);},removeItem:k=>saved.delete(k)};
 const sessionStorage={getItem:k=>sessions.get(k)||null,setItem:(k,v)=>sessions.set(k,v),removeItem:k=>sessions.delete(k)};
 const context=vm.createContext({window:{},localStorage,sessionStorage,crypto:webcrypto,TextEncoder});
 vm.runInContext(fs.readFileSync(path.join(root,'assets/demo-data.js'),'utf8'),context);
 vm.runInContext(fs.readFileSync(path.join(root,'assets/demo-core.js'),'utf8'),context);
 const {auth,db}=context.window.StoreDemo;
 await assert.rejects(()=>auth.signIn('customer','nova','SellerDemo123!'),/incorrect/);
 await assert.rejects(()=>auth.signIn('seller','nova','wrong'),/incorrect/);
 await auth.signIn('seller','nova','SellerDemo123!');
 assert.equal(auth.current('seller').id,'nova-tech');
 const beforeOrbit=JSON.stringify(db.store('orbit-supply'));
 assert.throws(()=>db.updateStore('orbit-supply',{name:'Hijacked'}),/another seller/);
 assert.throws(()=>db.saveProduct('nova-tech',{name:'Hijacked'},'watch'),/not found/);
 assert.throws(()=>db.setProductStatus('nova-tech','watch','archived'),/not found/);
 assert.throws(()=>db.setOrderStatus('nova-tech','DEMO-1041','Delivered'),/cannot/);
 const input={sellerId:'orbit-supply',name:'Test Product',summary:'A testing item',description:'Description',category:'Tech',price:39.95,stock:4,status:'active',sku:'TEST-001',image:'javascript:alert(1)',color:'#e7dbed',isNew:true};
 const created=db.saveProduct('nova-tech',input);
 assert.equal(created.sellerId,'nova-tech');assert.equal(created.image,'assets/products/placeholder.svg');assert.equal(db.store('nova-tech').products.length,5);
 assert.throws(()=>db.saveProduct('nova-tech',input),/SKU/);
 assert.throws(()=>db.saveProduct('nova-tech',{...input,sku:'OTHER',price:0}),/price/);
 assert.throws(()=>db.saveProduct('nova-tech',{...input,sku:'OTHER',stock:-1}),/Stock/);
 db.setProductStatus('nova-tech',created.id,'archived');assert(!db.catalog().some(p=>p.id===created.id));
 db.setProductStatus('nova-tech',created.id,'active');assert(db.catalog().some(p=>p.id===created.id));
 db.updateStore('nova-tech',{name:'Nova Test',tagline:'Hello',description:'Owned store',email:'demo@example.com',phone:'',location:''});
 assert.equal(JSON.stringify(db.store('orbit-supply')),beforeOrbit);
 const exported=db.exportStore('nova-tech');assert(exported.products.every(p=>p.sellerId==='nova-tech'));assert(!JSON.stringify(exported).includes('hash'));
 const snapshot=JSON.stringify(db.store('nova-tech'));failWrites=true;
 assert.throws(()=>db.setProductStatus('nova-tech',created.id,'draft'),/storage/);failWrites=false;
 assert.equal(JSON.stringify(db.store('nova-tech')),snapshot);
 auth.signOut('seller');assert.throws(()=>db.updateStore('nova-tech',{name:'No'}),/another seller/);
 await auth.register('seller',{name:'New Store',username:'new_seller',password:'NewDemoPass123!'});
 const newSeller=auth.current('seller');assert.equal(db.store(newSeller.id).products.length,0);
 await auth.register('customer',{name:'New Customer',username:'new_customer',password:'CustomerPass123!'});
 assert.equal(auth.current('customer').role,'customer');
 await assert.rejects(()=>auth.updateAccount('customer',{name:'X',email:'',currentPassword:'bad',password:'ChangedPass123!'}),/incorrect/);
 await auth.updateAccount('customer',{name:'Changed Name',email:'',currentPassword:'CustomerPass123!',password:'ChangedPass123!'});
 auth.signOut('customer');await assert.rejects(()=>auth.signIn('customer','new_customer','CustomerPass123!'),/incorrect/);
 await auth.signIn('customer','new_customer','ChangedPass123!');assert.equal(auth.current('customer').name,'Changed Name');
 auth.signOut('seller');assert.equal(auth.current('seller'),null);assert(auth.current('customer'));
 await auth.signIn('seller','orbit','SellerDemo123!');assert.equal(db.requireSeller('orbit-supply').products.length,4);
 assert.throws(()=>db.requireSeller('nova-tech'),/another seller/);
 console.log('PASS: demo authentication, role separation, seller isolation, product lifecycle, catalog, password changes, quota errors, and scoped exports.');
})().catch(error=>{console.error(error);process.exitCode=1;});
