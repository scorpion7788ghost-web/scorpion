"""Generate palette variables from the existing CSS, preserving product images.

Run after adding palette colors to a stylesheet. Shadows and image assets are
not recolored. The original plum palette remains each variable's fallback.
"""
from pathlib import Path
import colorsys
import re

ROOT = Path(__file__).resolve().parents[1]
colors = set()
pattern = re.compile(r'#[\da-fA-F]{3,8}\b')
files = [p for folder in ('assets', 'seller-site/assets') for p in (ROOT / folder).glob('*.css') if p.name not in ('themes.css', 'profile.css', 'polish.css')]
for path in files:
    source = path.read_text(encoding='utf-8')
    # Idempotent regeneration; unwrap only variables managed by this script.
    source = re.sub(r'var\(--palette-[a-f0-9]+,\s*(#[a-f0-9]+)\)', r'\1', source)
    def declaration(match):
        prop, value = match.groups()
        if prop.strip().endswith('shadow'):
            return prop + ':' + value
        def replace(color):
            token = color.group().lower()
            colors.add(token)
            return 'var(--palette-' + token[1:] + ',' + token + ')'
        return prop + ':' + pattern.sub(replace, value)
    source = re.sub(r'([\w-]+)\s*:([^;{}]+)', declaration, source)
    path.write_text(source, encoding='utf-8')

def convert(token, light, ocean, mono=False):
    value = token[1:]
    if len(value) in (3, 4):
        value = ''.join(c * 2 for c in value)
    rgb = tuple(int(value[i:i+2], 16) / 255 for i in (0, 2, 4))
    h, l, s = colorsys.rgb_to_hls(*rgb)
    alpha = value[6:]
    purple = 220 <= h * 360 <= 310
    green = 65 <= h * 360 <= 165
    if ocean and (purple or s < .12):
        h = 205 / 360
        s = max(s, .25)
    if ocean and green:
        h = 177 / 360
    if light:
        # Dark surfaces become pale; pale labels become deep, readable ink.
        l = .99 - .95 * l
        s = min(s, .55)
        if l > .65:
            s = min(s, .3)
    if mono: s = 0
    rgb = colorsys.hls_to_rgb(h, l, s)
    return '#' + ''.join(f'{round(c * 255):02x}' for c in rgb) + alpha

output = ['/* Generated by tools/build-themes.py. Original colors are fallbacks. */']
for theme, light, ocean in [('ocean-dark', False, True), ('black-dark', False, False), ('white-light', True, False)]:
    output.append('html[data-theme="' + theme + '"]{')
    output.extend('  --palette-' + color[1:] + ':' + convert(color, light, ocean, theme in ('black-dark','white-light')) + ';' for color in sorted(colors))
    output.append('}')
# Explicit canvas anchors and interaction contrast for all four designs.
output.extend([
 'html[data-theme="black-dark"]{--bg:#080808;--panel:#171717;--text:#ffffff;--muted:#bdbdbd;--accent:#ffffff;--lime:#ffffff;--line:#ffffff26}',
 'html[data-theme="white-light"]{--bg:#ffffff;--panel:#f7f7f7;--text:#111111;--muted:#555555;--accent:#111111;--lime:#111111;--line:#00000026}',
 'html[data-theme="ocean-dark"]{--bg:#101b27;--panel:#182a39;--text:#edf5fa;--muted:#a4bac9;--accent:#72c5e8;--lime:#94e8d3;--line:#d2eafa22}',
 'html[data-theme] body{background:var(--bg);color:var(--text)}',
 'html[data-theme] .site-header,html[data-theme] .seller-header{background:var(--bg)}',
 'html[data-theme$="light"] .primary-button,html[data-theme$="light"] .category-filters button.active,html[data-theme$="light"] .role-filters button.active{color:#fff}',
 'html[data-theme$="light"] input,html[data-theme$="light"] select,html[data-theme$="light"] textarea{color-scheme:light}',
])
result = '\n'.join(output) + '\n'
for folder in ('assets', 'seller-site/assets'):
    (ROOT / folder / 'themes.css').write_text(result, encoding='utf-8')
print(f'Generated four palettes covering {len(colors)} existing colors.')
